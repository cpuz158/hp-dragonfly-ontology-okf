def extract_okf_graph_from_viz(viz_path: Path) -> dict[str, Any]:
  """Extracts the exact window.BUNDLE JSON object generated by reference_agent.viewer."""
  html = viz_path.read_text(encoding="utf-8")
  m = re.search(r"window\.BUNDLE\s*=\s*(\{.*?\});\s*\n", html, re.DOTALL)
  if not m:
    return {"nodes": [], "edges": []}
  return json.loads(m.group(1))


