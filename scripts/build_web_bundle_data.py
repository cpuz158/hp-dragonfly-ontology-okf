def build_gql_query_library(bq_tables: list[dict[str, Any]]) -> list[dict[str, Any]]:
  """Builds 4 curated GQL queries matching `hp_dragonfly_ontology_graph` with precomputed results."""
  table_map = {t["table_name"]: t["rows"] for t in bq_tables}
  comp_by_part = {r["part_number"]: r for r in table_map["hardware_components_catalog"]}
  model_by_id = {r["model_id"]: r for r in table_map["dragonfly_series_models"]}
  diag_by_code = {r["diagnostic_code"]: r for r in table_map["diagnostic_codes_reference"]}

  # 1. GQL Query 1: Disassembly Precedence DAG (REQUIRES_REMOVAL_OF)
  q1_rows = []
  q1_nodes_map = {}
  q1_edges = []
  for dep in table_map["component_disassembly_deps"]:
    target_no = dep["target_part_number"]
    prereq_no = dep["prerequisite_part_number"]
    target = comp_by_part.get(target_no, {})
    prereq = comp_by_part.get(prereq_no, {})
    q1_rows.append({
        "dependency_id": dep["dependency_id"],
        "step_order": dep["step_order"],
        "target_part_number": target_no,
        "target_component": dep["target_component_name"],
        "prerequisite_part_number": prereq_no,
        "prerequisite_component": dep["prerequisite_component_name"],
        "fastener_screw_spec": dep["fastener_screw_spec"],
        "required_tools": dep["required_tools"],
        "manual_page_ref": dep["manual_page_ref"],
    })
    for pno, cname, cobj in [
        (target_no, dep["target_component_name"], target),
        (prereq_no, dep["prerequisite_component_name"], prereq),
    ]:
      if pno not in q1_nodes_map:
        q1_nodes_map[pno] = {
            "id": pno,
            "label": f"{cname}\n({pno})",
            "group": "HardwareComponent",
            "category": cobj.get("component_category", "Hardware"),
        }
    q1_edges.append({
        "from": target_no,
        "to": prereq_no,
        "label": f"Step {dep['step_order']}: REQUIRES_REMOVAL_OF",
    })

  # 2. GQL Query 2: Troubleshooting Case -> Affected Hardware Component & Triggered Diagnostic Code
  q2_rows = []
  q2_nodes_map = {}
  q2_edges = []
  for case in table_map["community_troubleshooting_cases"]:
    pno = case.get("affected_part_number") or ""
    dcode = case.get("error_or_diagnostic_code") or ""
    comp = comp_by_part.get(pno, {})
    diag = diag_by_code.get(dcode, {})
    q2_rows.append({
        "case_id": case["case_id"],
        "model_id": case["model_id"],
        "issue_category": case["issue_category"],
        "severity": case["severity"],
        "reported_symptom": case["reported_symptom"][:90] + "...",
        "affected_part_number": pno or "N/A",
        "component_name": comp.get("component_name", "Firmware / OS Config"),
        "error_or_diagnostic_code": dcode or "None",
        "resolving_softpaq_id": case.get("resolving_softpaq_id") or "FRU Replace",
        "requires_part_replacement": case["requires_part_replacement"],
    })
    cid = case["case_id"]
    q2_nodes_map[cid] = {
        "id": cid,
        "label": f"{cid}\n[{case['issue_category']}]",
        "group": "TroubleshootingCase",
    }
    if pno and comp:
      q2_nodes_map[pno] = {
          "id": pno,
          "label": f"{comp['component_name']}\n({pno})",
          "group": "HardwareComponent",
      }
      q2_edges.append({
          "from": cid,
          "to": pno,
          "label": "AFFECTS_COMPONENT",
      })
    if dcode and diag:
      q2_nodes_map[dcode] = {
          "id": dcode,
          "label": f"{dcode}\n({diag.get('diagnostic_category', '')})",
          "group": "DiagnosticCode",
      }
      q2_edges.append({
          "from": cid,
          "to": dcode,
          "label": "TRIGGERS_DIAGNOSTIC",
      })

  # 3. GQL Query 3: Multi-Hop Case -> Target FRU -> Prerequisite Disassembly Chain
  q3_rows = []
  q3_nodes_map = {}
  q3_edges = []
  for case in table_map["community_troubleshooting_cases"]:
    if not case.get("requires_part_replacement"):
      continue
    pno = case.get("affected_part_number")
    if not pno:
      continue
    comp = comp_by_part.get(pno, {})
    cid = case["case_id"]
    q3_nodes_map[cid] = {
        "id": cid,
        "label": f"{cid}\n({case['issue_category']})",
        "group": "TroubleshootingCase",
    }
    if comp:
      q3_nodes_map[pno] = {
          "id": pno,
          "label": f"{comp.get('component_name', pno)}\n({pno})",
          "group": "HardwareComponent",
      }
