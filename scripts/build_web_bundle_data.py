def parse_okf_markdown(rel_path: str, full_path: Path) -> dict[str, Any]:
  raw = full_path.read_text(encoding="utf-8")
  frontmatter: dict[str, Any] = {}
  body = raw
  m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", raw, re.DOTALL)
  if m:
    try:
      frontmatter = yaml.safe_load(m.group(1)) or {}
    except Exception:
      frontmatter = {}
    body = m.group(2).strip()

  parts = rel_path.split("/")
  category = parts[0] if len(parts) > 1 else "root"
  page_info = PDF_PAGE_MAP.get(
      rel_path,
      {
          "page": 1,
          "section_en": "HP Dragonfly Folio G3 Service Manual (N17344-001)",
          "section_ko": "HP Dragonfly Folio G3 서비스 매뉴얼 (N17344-001)",
      },
  )
  return {
      "id": rel_path.replace(".md", ""),
      "rel_path": rel_path,
      "category": category,
      "filename": full_path.name,
      "frontmatter": frontmatter,
      "body": body,
      "raw": raw,
      "pdf_page": page_info["page"],
      "pdf_section_en": page_info["section_en"],
      "pdf_section_ko": page_info["section_ko"],
  }


def collect_okf_files() -> list[dict[str, Any]]:
  files: list[dict[str, Any]] = []
  order_categories = [
      "root",
      "datasets",
      "tables",
      "references",
      "metrics",
      "computations",
      "playbooks",
  ]
  for p in sorted(BUNDLE_DIR.rglob("*.md")):
    rel = str(p.relative_to(BUNDLE_DIR))
    files.append(parse_okf_markdown(rel, p))

  files.sort(
      key=lambda x: (
          order_categories.index(x["category"])
          if x["category"] in order_categories
          else 99,
          x["rel_path"],
      )
  )
  return files


def collect_git_commits() -> list[dict[str, Any]]:
  try:
    out = subprocess.check_output(
        [
            "git",
            "log",
            "-n",
            "10",
            "--pretty=format:%H|%h|%an|%ae|%ad|%s",
            "--date=iso",
        ],
        cwd=str(WORKSPACE_ROOT),
        text=True,
    )
    commits = []
    for line in out.strip().splitlines():
      parts = line.split("|", 5)
      if len(parts) == 6:
        stat_out = subprocess.check_output(
            ["git", "show", "--stat", "--format=", parts[0]],
            cwd=str(WORKSPACE_ROOT),
            text=True,
        ).strip()
        commits.append({
            "hash": parts[0],
            "short_hash": parts[1],
            "author": parts[2],
            "email": parts[3],
            "date": parts[4],
            "subject": parts[5],
            "stat": stat_out,
        })
    return commits
  except Exception as e:
    return [{"error": str(e)}]


